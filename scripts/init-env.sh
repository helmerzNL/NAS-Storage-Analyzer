#!/bin/sh
# Creates the settings that docker-compose.yml needs, with random secrets. Never overwrites.
#
#   ./scripts/init-env.sh                          writes .env (data folder, shares folder, database password, encryption key, setup token)
#   ./scripts/init-env.sh --secrets                writes ./secrets/* for docker-compose.secrets.yml, and the rest of .env
#   ./scripts/init-env.sh --data-path /srv/nasa    where the database lives (DATA_PATH); must be an absolute folder of this machine
#   ./scripts/init-env.sh --shares-dir /mnt/user   the folder that holds the shares (NASA_SHARES_DIR); must be absolute too
#
# The encryption key protects the stored SMB passwords. Back it up with the database: without it
# those passwords cannot be decrypted (shares then have to be re-entered).
#
# DATA_PATH and NASA_SHARES_DIR are never relative: a relative path is resolved by whatever tool starts the
# stack (Dockhand on Unraid has put ./data in the RAM disk), so this script refuses one. Without the options it
# picks /mnt/user/appdata/nas-storage-analyzer on Unraid and /srv/nas-storage-analyzer elsewhere; check them.
set -eu
cd "$(dirname "$0")/.."
umask 077

mode=env data_path="" shares_dir=""
while [ $# -gt 0 ]; do
  case "$1" in
    --secrets) mode=secrets ;;
    --data-path) shift; data_path="${1:-}" ;;
    --data-path=*) data_path="${1#--data-path=}" ;;
    --shares-dir) shift; shares_dir="${1:-}" ;;
    --shares-dir=*) shares_dir="${1#--shares-dir=}" ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
  shift
done

if [ -d /mnt/user ]; then # Unraid
  : "${data_path:=/mnt/user/appdata/nas-storage-analyzer}"
  : "${shares_dir:=/mnt/user}"
else
  : "${data_path:=/srv/nas-storage-analyzer}"
  : "${shares_dir:=/srv/shares}"
fi
for pair in "DATA_PATH:$data_path" "NASA_SHARES_DIR:$shares_dir"; do
  case "${pair#*:}" in
    /*) ;;
    *) echo "${pair%%:*} is \"${pair#*:}\", a relative path: give an absolute folder of this machine (a relative path is resolved by whatever tool starts the stack, not by Docker)." >&2; exit 1 ;;
  esac
done

rand() { # rand <bytes>: base64 of random bytes, on one line
  if command -v openssl >/dev/null 2>&1; then openssl rand -base64 "$1" | tr -d '\n'
  else head -c "$1" /dev/urandom | base64 | tr -d '\n'; fi
}
plain() { rand "$1" | tr -d '/+=' ; } # letters and digits only: safe in a URL and in .env

if [ "$mode" = secrets ]; then
  [ -e secrets/db_password ] || [ -e secrets/encryption_key ] && { echo "secrets/ already has files; not overwriting." >&2; exit 1; }
  mkdir -p secrets && chmod 700 secrets
  plain 32 > secrets/db_password
  rand 32 > secrets/encryption_key
  # Readable inside the container (non-root user); the 0700 directory keeps other host users out.
  chmod 444 secrets/db_password secrets/encryption_key
  [ -e .env ] || {
    printf 'DATA_PATH=%s\nNASA_SHARES_DIR=%s\nNASA_SETUP_TOKEN=%s\n' "$data_path" "$shares_dir" "$(plain 24)" > .env
  }
  echo "Created secrets/db_password and secrets/encryption_key."
  echo "Data folder: $data_path   Shares folder: $shares_dir   (both in .env; change them there if they are not right)"
  echo "Start with: docker compose -f docker-compose.yml -f docker-compose.secrets.yml up -d"
  exit 0
fi

[ -e .env ] && { echo ".env already exists; not overwriting. See .env.example for all settings." >&2; exit 1; }
cat > .env <<ENV
# Generated by scripts/init-env.sh. All settings and their meaning: .env.example
# latest is the stable image; beta is the build every change lands in first (use another DATA_PATH for it).
NASA_TAG=latest
# Absolute folder of this machine that holds the database. Never relative; see .env.example.
DATA_PATH=$data_path
# Absolute folder of this machine that holds the mounted shares (read-only in the containers).
NASA_SHARES_DIR=$shares_dir
NASA_DB_PASSWORD=$(plain 32)
NASA_ENCRYPTION_KEY=$(rand 32)
# Needed once, to create the first administrator in the browser. You may delete it afterwards.
NASA_SETUP_TOKEN=$(plain 24)
ENV
chmod 600 .env
echo "Created .env."
echo "Data folder: $data_path   Shares folder: $shares_dir   (change them in .env if they are not right)"
echo "Start with: docker compose up -d"
echo "Then open http://127.0.0.1:8080 and use the setup token from .env."
